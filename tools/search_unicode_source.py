"""Unicode normalization source emitted only by the normal build entry point."""
from pathlib import Path
import unicodedata
import json
import xml.etree.ElementTree as ET


def write_search_unicode_source(path: Path) -> None:
    mappings, values, classes, compositions = [], [], [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        combining = unicodedata.combining(char)
        if combining:
            classes.append((cp, combining))
        # Hangul decomposition/composition is algorithmic in the consumer.
        normalized = unicodedata.normalize("NFKD", char)
        if normalized != char and not 0xAC00 <= cp < 0xD7A4:
            mappings.append((cp, len(values), len(normalized)))
            values.extend(map(ord, normalized))
        canonical = unicodedata.decomposition(char)
        if canonical and not canonical.startswith("<"):
            pair = [int(part, 16) for part in canonical.split()]
            if len(pair) == 2 and unicodedata.normalize("NFC", "".join(map(chr, pair))) == char:
                compositions.append((pair[0], pair[1], cp))
    lines = [f"// Unicode {unicodedata.unidata_version}; generated by tools/build.py.",
             "struct SearchUnicodeMapping { uint32_t cp, offset, count; };",
             "struct SearchUnicodeClass { uint32_t cp, value; };",
             "struct SearchUnicodeComposition { uint32_t first, second, result; };"]
    def emit(declaration, entries):
        lines.append(declaration + "[] = {")
        lines.extend("    {" + ",".join(map(str, entry)) + "}," for entry in entries)
        lines.append("};")
    emit("static constexpr SearchUnicodeMapping search_unicode_mappings", mappings)
    lines.append("static constexpr uint32_t search_unicode_values[] = {")
    for offset in range(0, len(values), 24):
        lines.append("    " + ",".join(map(str, values[offset:offset + 24])) + ",")
    lines.append("};")
    emit("static constexpr SearchUnicodeClass search_unicode_classes", classes)
    emit("static constexpr SearchUnicodeComposition search_unicode_compositions", sorted(compositions))
    source = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != source:
        path.write_text(source, encoding="utf-8")
    write_native_search_rules(path.with_name("search_native_rules.inc"))


def write_native_search_rules(path: Path) -> None:
    structures = path.parent.parent / "data/upstream/df-structures"
    def enum(file, name):
        root = ET.parse(structures / file).getroot()
        value = -1
        for item in root.find(f"enum-type[@type-name='{name}']").findall("enum-item"):
            value = int(item.get("value")) if item.get("value") else value + 1
            yield value, item
    quote = lambda text: json.dumps(text, ensure_ascii=True)
    types = {item.get("name"): value for value, item in enum("df.d_basics.xml", "item_type")}
    lines = ["// Pinned native enum metadata; generated by the normal build entry.",
             "struct SearchNativeJobRule { int16_t job, product; const char *name, *material; bool transfers_material; };",
             "static constexpr SearchNativeJobRule search_native_job_rules[] = {"]
    for value, item in enum("df.job.xml", "job_type"):
        attrs = {attr.get("name"): attr.get("value", "") for attr in item.findall("item-attr")}
        if attrs.get("type") != "Manufacture" or attrs.get("item", "NONE") == "NONE":
            continue
        # CONSTRUCT_* rules describe an object built from the selected stock.
        # Smelting, extraction and other transformations require separate rules.
        transfer = item.get("original-name", "").startswith("CONSTRUCT_")
        lines.append(f"    {{{value},{types[attrs['item']]},{quote(item.get('name'))},{quote(attrs.get('material', ''))},{str(transfer).lower()}}},")
    lines += ["};", "struct SearchStockpileColumn { int32_t mode; const char *name; bool category, material; };",
              "static constexpr SearchStockpileColumn search_stockpile_columns[] = {"]
    for value, item in enum("df.building.xml", "stockpile_list"):
        name, original = item.get("name"), item.get("original-name", "")
        category = any(a.get("name") == "is_category" and a.get("value") == "true" for a in item.findall("item-attr"))
        material = ("_MAT" in original or name.startswith(("Stone", "Bars", "Blocks", "Rough", "Cut", "Thread", "Cloth"))
                    or name in ("Wood", "Coins", "LeatherType")) and not name.endswith("Color")
        lines.append(f"    {{{value},{quote(name)},{str(category).lower()},{str(material).lower()}}},")
    lines.append("};")
    lines += ["struct SearchNativeProfession { int16_t value; const char *caption; };",
              "static constexpr SearchNativeProfession search_native_professions[] = {"]
    for value, item in enum("df.d_basics.xml", "profession"):
        caption = item.find("item-attr[@name='caption']")
        if caption is not None:
            lines.append(f"    {{{value},{quote(caption.get('value'))}}},")
    lines.append("};")
    lines += ["struct SearchNativeMaterialFlag { unsigned bit; const char *name, *category; };",
              "static constexpr SearchNativeMaterialFlag search_native_material_flags[] = {"]
    categories = {"IS_STONE": "stone", "IS_METAL": "metal", "WOOD": "wood", "THREAD_PLANT": "cloth",
                  "SILK": "silk", "YARN": "yarn", "LEATHER": "leather", "BONE": "bone", "SHELL": "shell",
                  "SOAP": "soap", "TOOTH": "tooth", "HORN": "horn", "PEARL": "pearl"}
    for value, item in enum("df.d_basics.xml", "material_flags"):
        name = item.get("name")
        if value >= 0:
            lines.append(f"    {{{value},{quote(name)},{quote(categories.get(name, ''))}}},")
    lines.append("};")
    lines += ["struct SearchNativeToolUse { int16_t value; const char *name; };",
              "static constexpr SearchNativeToolUse search_native_tool_uses[] = {"]
    for value, item in enum("df.d_basics.xml", "tool_uses"):
        if value >= 0:
            lines.append(f"    {{{value},{quote(item.get('name'))}}},")
    lines.append("};")
    lines += ["struct SearchNativeDefinitionFlag { const char *type; unsigned bit; const char *name; };",
              "static constexpr SearchNativeDefinitionFlag search_native_definition_flags[] = {"]
    definitions = ET.parse(structures / "df.itemdef.xml").getroot()
    for item in definitions.findall("class-type"):
        flags = item.find("df-flagarray[@name='flags']")
        if flags is None or not item.get("type-name", "").startswith("itemdef_"):
            continue
        for value, flag in enum("df.itemdef.xml", flags.get("index-enum")):
            if value >= 0:
                lines.append(f"    {{{quote(item.get('type-name'))},{value},{quote(flag.get('name'))}}},")
    lines.append("};")
    source = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != source:
        path.write_text(source, encoding="utf-8")
